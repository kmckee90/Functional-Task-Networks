"""
generate_baseline_tables.py — Build baseline-comparison tables that
combine the FTN results (exp2/exp6 default) with NoMask + FixedMask
baselines for synthetic and MNIST shared-shuffle.

Outputs:
    paper/neurips/tables/baselines_synthetic.tex
    paper/neurips/tables/baselines_mnist.tex
    paper/arxiv/tables/baselines_synthetic.tex
    paper/arxiv/tables/baselines_mnist.tex
"""

from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np


def _load(path):
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


def _stat(runs, path):
    vals = []
    for r in runs:
        cur = r
        for k in path:
            cur = cur[k]
        if cur is None:
            continue
        vals.append(float(cur))
    if not vals:
        return float("nan"), float("nan")
    return float(np.mean(vals)), float(np.std(vals))


def _head_start_per_run(r):
    vals = [
        h["task_loss_with_mask"]
        for h in r["head_start"][1:]
        if h["task_loss_with_mask"] is not None
    ]
    return float(np.mean(vals)) if vals else float("nan")


def collect_rows(family: str):
    """Return rows = list of (label, n, acc, fm, bwt, head, share)."""
    rows = []
    if family == "synthetic":
        # NoMask, FixedMask from baselines_synthetic.json
        b = _load("results/baselines_synthetic.json")
        # FTN (correlated, default) from exp2_synthetic.json (correlated rows)
        e2 = _load("results/exp2_synthetic.json")
    else:
        b = _load("results/baselines_mnist_shared.json")
        e2 = _load("results/exp6_mnist_shared.json")

    # NoMask
    if b:
        rs = [r for r in b["runs"].values() if r["method"] == "NoMask"]
        if rs:
            rows.append(_row("NoMask", rs))
        rs = [r for r in b["runs"].values() if r["method"] == "FixedMask"]
        if rs:
            rows.append(_row("FixedMask", rs))
    if e2:
        if family == "synthetic":
            rs = [r for r in e2["runs"].values() if r.get("orthogonal", False) is False]
        else:
            rs = list(e2["runs"].values())
        if rs:
            rows.append(_row("FTN (AnnealSTE, $S{=}30$)", rs))
    return rows


def _row(label, rs):
    acc_m, acc_s = _stat(rs, ["summary_stored", "ACC"])
    fm_m, fm_s = _stat(rs, ["summary_stored", "FM"])
    bwt_m, bwt_s = _stat(rs, ["summary_stored", "BWT"])
    sc_m, sc_s = _stat(rs, ["sharing_corr"])
    head_per = [_head_start_per_run(r) for r in rs]
    head_m = float(np.nanmean(head_per))
    head_s = float(np.nanstd(head_per))
    return {
        "label": label,
        "n": len(rs),
        "acc": (acc_m, acc_s),
        "fm": (fm_m, fm_s),
        "bwt": (bwt_m, bwt_s),
        "head": (head_m, head_s),
        "share": (sc_m, sc_s),
    }


def write_table(family: str, dest_paths: list[str]) -> None:
    rows = collect_rows(family)
    if not rows:
        return
    fname = "synthetic" if family == "synthetic" else "MNIST shared-shuffle"
    label = "tab:baselines_synthetic" if family == "synthetic" else "tab:baselines_mnist"
    out = []
    out.append("% Auto-generated by experiments/generate_baseline_tables.py")
    out.append("\\begin{table}[t]\n\\centering\n\\small")
    out.append(
        "\\caption{Baseline comparison on " + fname + ". NoMask trains "
        "the full network without any per-task mask (full parameter sharing); "
        "FixedMask uses deterministic disjoint blocks of size $k$ per task "
        "(no transfer, oracle no-forgetting). FTN closes the FM gap between "
        "NoMask and FixedMask while recovering non-trivial concept-sharing "
        "structure that both baselines lack ($r_{\\mathrm{share}}=0$ by "
        "construction). Mean$\\pm$std over 8 seeds.}"
    )
    out.append(f"\\label{{{label}}}")
    out.append("\\begin{tabular}{lccccc}")
    out.append("\\toprule")
    out.append(
        "Method & ACC$\\uparrow$ & FM$\\downarrow$ & BWT$\\uparrow$ "
        "& Head-start$\\downarrow$ & $r_{\\mathrm{share}}\\uparrow$ \\\\"
    )
    out.append("\\midrule")
    for r in rows:
        head_str = (
            "--" if not np.isfinite(r["head"][0])
            else f"{r['head'][0]:.3f}\\,$\\pm$\\,{r['head'][1]:.3f}"
        )
        out.append(
            f"{r['label']} "
            f"& {r['acc'][0]:.3f}\\,$\\pm$\\,{r['acc'][1]:.3f} "
            f"& {r['fm'][0]:.3f}\\,$\\pm$\\,{r['fm'][1]:.3f} "
            f"& {r['bwt'][0]:+.3f}\\,$\\pm$\\,{r['bwt'][1]:.3f} "
            f"& {head_str} "
            f"& {r['share'][0]:.3f}\\,$\\pm$\\,{r['share'][1]:.3f} \\\\"
        )
    out.append("\\bottomrule")
    out.append("\\end{tabular}")
    out.append("\\end{table}")
    text = "\n".join(out) + "\n"
    for p in dest_paths:
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write(text)
        print(f"  Wrote: {p}")


def main():
    os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    print(f"Working directory: {os.getcwd()}")
    write_table(
        "synthetic",
        [
            "paper/neurips/tables/baselines_synthetic.tex",
            "paper/arxiv/tables/baselines_synthetic.tex",
        ],
    )
    write_table(
        "mnist",
        [
            "paper/neurips/tables/baselines_mnist.tex",
            "paper/arxiv/tables/baselines_mnist.tex",
        ],
    )
    print("Done.")


if __name__ == "__main__":
    main()
