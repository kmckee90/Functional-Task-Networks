"""
generate_revision_tables.py — build LaTeX tables from results/revision_*.json.

Reads the per-task aggregated results and emits:
  paper/neurips/tables/revision_main.tex             # main paper table
  paper/neurips/tables/revision_per_benchmark.tex    # appendix detail
  paper/neurips/tables/revision_supportsize.tex      # support-size sweep
  paper/arxiv/tables/revision_*.tex                  # arxiv mirrors

Run after the parallel sweep has completed and shards have been merged.
"""
from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np


TASK_DISPLAY = {
    "synthetic": "Synthetic (correlated)",
    "mnist_shared": "Shared-shuffle MNIST",
    "permuted": "PermutedMNIST",
    "rotated": "RotatedMNIST",
}

METHOD_ORDER = [
    "NoMask",
    "NoMask+ER",
    "SupSup",
    "Progressive",
    "FixedMask",
    "FixedMask+Router",
    "FTN_RandMask",
    "FTN",
    "FTN+Router",
    "FTN_noreplay",
]

METHOD_DISPLAY = {
    "NoMask": "NoMask (naive seq.)",
    "NoMask+ER": "NoMask + ER (random replay)",
    "SupSup": "SupSup (frozen backbone, learned mask)",
    "Progressive": "Progressive Nets (per-task column)",
    "FixedMask": "FixedMask (oracle ID at eval)",
    "FixedMask+Router": "FixedMask + retrieval router",
    "FTN_RandMask": "FTN, random per-batch masks (ablation)",
    "FTN": "FTN (ours)",
    "FTN+Router": "FTN + retrieval router (eval-only)",
    "FTN_noreplay": "FTN, no replay",
}


def fmt(mean, std, dec=3):
    if mean is None or np.isnan(mean):
        return "--"
    if std is None or np.isnan(std):
        return f"${mean:.{dec}f}$"
    return f"${mean:.{dec}f} \\pm {std:.{dec}f}$"


def gather_results(suffix: str = "") -> dict:
    """Returns {task_family: {method: {metric: (mean,std)}}}."""
    out: dict = {}
    for task in TASK_DISPLAY.keys():
        path = f"results/revision_{task}{suffix}.json"
        if not os.path.exists(path):
            continue
        with open(path) as f:
            data = json.load(f)
        agg = data.get("aggregated", {})
        for method, by_n in agg.items():
            # Only the "256" (default support size) entry feeds the main table
            entry = by_n.get("256") or next(iter(by_n.values()))
            metrics = {}
            for fld in ("ACC", "FM", "BWT"):
                key = f"summary_reconfig.{fld}"
                if key in entry:
                    metrics[fld] = (entry[key]["mean"], entry[key]["std"])
            if "head_start_mean" in entry:
                metrics["HS"] = (entry["head_start_mean"]["mean"],
                                 entry["head_start_mean"]["std"])
            metrics["n_seeds"] = entry.get("n_seeds", 0)
            out.setdefault(task, {})[method] = metrics
    return out


def emit_main_table(results: dict, path: str) -> None:
    """One row per (task, method); reconfig protocol."""
    lines = [
        "% Auto-generated by experiments/generate_revision_tables.py.",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\caption{Standard CL benchmarks under the reconfig (no-task-identity) protocol. "
        "All comparators see the same labeled support set at evaluation; no method "
        "receives task identity. Mean$\\pm$std over 5 seeds. Higher ACC and BWT, "
        "lower FM and head-start (HS) loss, are better. Within each benchmark, the "
        "best non-oracle ACC and lowest FM are shown.}",
        "\\label{tab:revision_main}",
        "\\begin{tabular}{llllll}",
        "\\toprule",
        "Task & Method & ACC$\\uparrow$ & FM$\\downarrow$ & BWT$\\uparrow$ & HS$\\downarrow$ \\\\",
        "\\midrule",
    ]
    for task in TASK_DISPLAY.keys():
        if task not in results:
            continue
        first = True
        for method in METHOD_ORDER:
            if method not in results[task]:
                continue
            m = results[task][method]
            tlabel = TASK_DISPLAY[task] if first else ""
            first = False
            mlabel = METHOD_DISPLAY.get(method, method)
            row = (
                f"{tlabel} & {mlabel} & "
                f"{fmt(*m.get('ACC', (None,None)))} & "
                f"{fmt(*m.get('FM', (None,None)))} & "
                f"{fmt(*m.get('BWT', (None,None)))} & "
                f"{fmt(*m.get('HS', (None,None)))} \\\\"
            )
            lines.append(row)
        lines.append("\\midrule")
    if lines[-1] == "\\midrule":
        lines.pop()
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"  wrote {path}")


def emit_per_benchmark_table(results: dict, path: str) -> None:
    """Same layout as main but with a different label and caption."""
    emit_main_table(results, path)
    # Re-stamp the label/caption so the appendix copy doesn't collide.
    with open(path) as f:
        content = f.read()
    content = content.replace(
        "\\label{tab:revision_main}", "\\label{tab:revision_per_benchmark}",
    )
    content = content.replace(
        "Standard CL benchmarks under",
        "Standard CL benchmarks (per-benchmark detail) under",
    )
    with open(path, "w") as f:
        f.write(content)


def emit_supportsize_table(suffix: str = "_support_size") -> None:
    """FTN with reconfig_batch_size in {1,5,10,50,256}."""
    rows: dict = {}
    for task in ("permuted", "rotated", "synthetic"):
        path = f"results/revision_{task}{suffix}.json"
        if not os.path.exists(path):
            continue
        with open(path) as f:
            data = json.load(f)
        agg = data.get("aggregated", {}).get("FTN", {})
        for n_str, entry in agg.items():
            metrics = {}
            for fld in ("ACC", "FM", "BWT"):
                key = f"summary_reconfig.{fld}"
                if key in entry:
                    metrics[fld] = (entry[key]["mean"], entry[key]["std"])
            if "head_start_mean" in entry:
                metrics["HS"] = (entry["head_start_mean"]["mean"],
                                 entry["head_start_mean"]["std"])
            metrics["n_seeds"] = entry.get("n_seeds", 0)
            rows[(task, int(n_str))] = metrics

    lines = [
        "% Auto-generated by experiments/generate_revision_tables.py.",
        "\\begin{table}[h]",
        "\\centering",
        "\\small",
        "\\caption{Support-set size sensitivity for FTN. Mean$\\pm$std over seeds.}",
        "\\label{tab:revision_supportsize}",
        "\\begin{tabular}{llllll}",
        "\\toprule",
        "Task & $n$ & ACC$\\uparrow$ & FM$\\downarrow$ & BWT$\\uparrow$ & HS$\\downarrow$ \\\\",
        "\\midrule",
    ]
    last_task = None
    for (task, n), m in sorted(rows.items()):
        tlabel = TASK_DISPLAY[task] if task != last_task else ""
        if task != last_task and last_task is not None:
            lines.append("\\midrule")
        last_task = task
        lines.append(
            f"{tlabel} & {n} & "
            f"{fmt(*m.get('ACC', (None,None)))} & "
            f"{fmt(*m.get('FM', (None,None)))} & "
            f"{fmt(*m.get('BWT', (None,None)))} & "
            f"{fmt(*m.get('HS', (None,None)))} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    out_path = "paper/neurips/tables/revision_supportsize.tex"
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"  wrote {out_path}")


